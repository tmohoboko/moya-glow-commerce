import {test,expect} from '@playwright/test';
const day = () => new Intl.DateTimeFormat('en-CA',{timeZone:'Africa/Johannesburg',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date(Date.now()+86400000));

test('BOOKING-001 customer request → staff quote → acceptance → slot → invoice → reschedule → cancel',async({page,browser})=>{
 test.skip(Boolean(process.env.BASE_URL),'Privileged staff fixture exists only in the disposable local CI database.');
 const staffContext=await browser.newContext();
 const staff=await staffContext.newPage();
 try{
  await staff.goto('/account');
  await staff.getByLabel('Email',{exact:true}).fill('salon-qa@example.com');
  await staff.getByLabel('Password',{exact:true}).fill('ci-only-salon-password');
  await staff.getByRole('button',{name:'Log in',exact:true}).click();
  await staff.getByRole('button',{name:'Open salon calendar'}).click();
  await staff.getByText('Opening hours · Calendar closed',{exact:true}).click();
  await staff.getByLabel('Offer appointment slots').check();
  for(const name of ['Monday','Tuesday','Wednesday','Thursday','Friday','Saturday','Sunday'])await staff.getByLabel(name,{exact:true}).check();
  await staff.getByRole('button',{name:'Save opening hours',exact:true}).click();
  await expect(staff.getByText('Opening hours · Calendar open',{exact:true})).toBeVisible();
  await page.goto('/account');
  await page.getByRole('button',{name:'New here? Create an account'}).click();
  await page.getByLabel('Email',{exact:true}).fill(`journey-${crypto.randomUUID()}@example.com`);
  await page.getByLabel('Password',{exact:true}).fill('local-browser-test-password');
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await expect(page.getByRole('heading',{name:'My account',exact:true})).toBeVisible();
  await page.goto('/book?service=massage-full-body-450');
  const customer='Journey '+crypto.randomUUID();
  await page.getByLabel('Your name',{exact:true}).fill(customer);
  await page.getByLabel('Contact number',{exact:true}).fill('0800000000');
  await page.getByLabel('Treatment details',{exact:true}).fill('Full body massage and confirmation of duration.');
  await page.getByRole('button',{name:'Request quotation',exact:true}).click();
  await expect(page.getByText('Awaiting quotation',{exact:true})).toBeVisible();
  await staff.getByRole('button',{name:'Refresh calendar',exact:true}).click();
  const quote=staff.locator('[data-staff-quote-id]').filter({has:staff.getByText(customer,{exact:false})});
  await quote.getByLabel('Quoted total (R)',{exact:true}).fill('475');
  await quote.getByLabel('Treatment duration (minutes)',{exact:true}).fill('60');
  await quote.getByLabel('Quotation details and payment terms',{exact:true}).fill('Full body treatment, 60 minutes. Pay at appointment.');
  await quote.getByRole('button',{name:'Issue quotation',exact:true}).click();
  await expect(quote.getByRole('button',{name:'Issue revised quotation',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Refresh appointments',exact:true}).click();
  await page.getByRole('button',{name:'Accept quotation',exact:true}).click();
  await page.getByLabel('Appointment date',{exact:true}).fill(day());
  const bookingForm=page.getByRole('form',{name:'Appointment booking form'});
  await expect(bookingForm.getByRole('button',{name:'Confirm appointment',exact:true})).toBeDisabled();
  await bookingForm.getByRole('button',{name:'Week',exact:true}).click();
  await expect(bookingForm.locator('[data-slot-day]')).toHaveCount(7);
  await bookingForm.locator(`[data-slot-day="${day()}"]`).getByRole('button').first().click();
  await expect(bookingForm.getByRole('button',{name:'Confirm appointment',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Confirm appointment',exact:true}).click();
  await expect(page.getByText('Confirmed',{exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByText('Confirmed',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'View invoice',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Your appointment invoice'})).toBeVisible();
  await expect(page.locator('.invoice-total strong')).toContainText('475');
  await expect(page.getByText('Payment due',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Back to appointments',exact:true}).click();
  const download=page.waitForEvent('download');
  await page.getByRole('link',{name:'Download calendar event'}).click();
  expect((await download).suggestedFilename()).toMatch(/lbeauty-.*\.ics/);
  await page.getByRole('button',{name:'Reschedule',exact:true}).click();
  await page.getByLabel('Appointment date',{exact:true}).fill(day());
  await page.getByRole('group',{name:'Available appointment times'}).getByRole('button').nth(2).click();
  await page.getByRole('button',{name:'Confirm new time',exact:true}).click();
  await expect(page.getByRole('button',{name:'Reschedule',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Cancel appointment',exact:true}).click();
  await expect(page.getByText('Cancelled',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'View invoice',exact:true}).click();
  await expect(page.getByText('Appointment: Cancelled · Invoice: Voided')).toBeVisible();
  await expect(page.getByRole('button',{name:'Pay invoice in Stripe test mode'})).toHaveCount(0);
  for(const width of [320,375]){
   await staff.setViewportSize({width,height:812});
   expect(await staff.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  }
  await staff.getByRole('button',{name:'Week',exact:true}).click();
  await expect(staff.getByRole('region',{name:'Week appointment calendar'}).locator('.calendar-column')).toHaveCount(7);
  expect(await staff.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await staff.screenshot({path:`${process.env.QA_SCREENSHOT_DIR||'qa'}/booking-salon.png`,fullPage:true});
 }finally{await staffContext.close()}
});
